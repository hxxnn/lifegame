export const QUEST_POOL: QuestDef[] = [
  ...(Object.keys(RAW) as StatId[]).flatMap((stat) =>
    RAW[stat].map(([tier, title, desc, unlockLevel], i): QuestDef => ({
      id: `${stat}-${String(i + 1).padStart(2, '0')}`,
      stat,
      tier,
      title,
      desc,
      baseXp: BALANCE.tierBaseXp[tier],
      ...(tier === 3 ? { requires: { stat, level: BALANCE.tierUnlockLevel[3] } } : {}),
      ...(tier === 4 ? { requires: { stat, level: BALANCE.tierUnlockLevel[4] } } : {}),
      ...(tier === 5 ? { requires: { stat, level: unlockLevel! } } : {}),
    })),
  ),
  ...FIXED.map((f): QuestDef => ({ ...f, tier: 1, baseXp: BALANCE.tierBaseXp[1], fixed: true })),
];

export const QUEST_BY_ID: Record<string, QuestDef> = Object.fromEntries(QUEST_POOL.map((q) => [q.id, q]));
